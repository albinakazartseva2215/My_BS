-- ПЕРЕСМОТР РАНЕЕ ЯВНО ПОДТВЕРЖДЁННОГО РЕШЕНИЯ. Документ схемы (раздел
-- "Спорные решения") и server/README.md до этой миграции фиксировали:
-- "мастера не логинятся, роли 'мастер' в users.role не существует —
-- решение подтверждено явно с постановщиком задачи". Требование новой
-- итерации — явно и прямо противоположное: роли хранить списком, один
-- человек может быть мастером и администратором одновременно. Это не
-- тихая отмена прежнего решения, а такой же явный пересмотр по прямому
-- запросу того же постановщика задачи — подробности и обоснование в
-- db-schema.md, "Спорные решения".

-- users.role (единственное значение из 'client'/'admin') заменяется на
-- отдельную таблицу — ролей у одного пользователя может быть несколько.
CREATE TABLE user_roles (
  user_id  INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role     TEXT NOT NULL CHECK (role IN ('client','admin','master')),
  PRIMARY KEY (user_id, role)
);

-- Переносим уже существующие одиночные роли, ничего не теряя.
INSERT INTO user_roles (user_id, role) SELECT id, role FROM users;

ALTER TABLE users DROP COLUMN role;

-- Профиль мастера может (необязательно) быть привязан к учётной записи
-- пользователя — тогда у этого пользователя должна быть роль 'master'
-- (инвариант проверяется в коде приложения при связывании: SQLite не
-- умеет CHECK через две таблицы). NULL — по-прежнему обычный случай:
-- профиль мастера без логина, как было раньше.
ALTER TABLE masters ADD COLUMN user_id INTEGER REFERENCES users(id);
CREATE UNIQUE INDEX ux_masters_user_id ON masters(user_id) WHERE user_id IS NOT NULL;
