// Подтверждение записи — этот заход ("сверстай экран подтверждения записи
// и экран успеха"). В прототипе это два разных файла подряд — «Booking · 4 ·
// Вход в потоке» и «Booking · 5 · Подтверждение» — но в реальном API это
// физически не разнести на два шага так же, как в прототипе: подтвердить
