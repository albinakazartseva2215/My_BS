// booking-4.html — это то, что в прототипе называлось «Booking · 5 ·
// Подтверждение» (плюс форма из «Booking · 4»), а BOOKING_SUCCESS_URL ниже
// (booking-5.html) — прототиповский «Booking · 6 · Успех». Если клиент уже
// вошёл (например, вернулся на этот шаг позже), форма слева не показывается
// вообще — см. js/booking-4.js.
