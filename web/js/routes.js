// клиент (requireAuth), поэтому вход и подтверждение здесь — один экран
// (слева форма входа/регистрации, справа сводка визита, задание прямо
// требует такую раскладку), а не два. Отсюда и сдвиг имени файла: наш
// booking-4.html — это то, что в прототипе называлось «Booking · 5 ·
// Подтверждение» (плюс форма из «Booking · 4»), а BOOKING_SUCCESS_URL ниже
// (booking-5.html) — прототиповский «Booking · 6 · Успех». Если клиент уже
// вошёл (например, вернулся на этот шаг позже), форма слева не показывается
// вообще — см. js/booking-4.js.
export const BOOKING_CONFIRM_URL = 'booking-4.html';

// Booking · 6 · Успех — см. объяснение сдвига номеров выше.
export const BOOKING_SUCCESS_URL = 'booking-5.html';

